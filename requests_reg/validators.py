"""
Проверка идентификаторов представителя (ИНН, СНИЛС).

Поля показываются у машиночитаемой доверенности, но НЕ обязательны: на
Госуслугах их для МЧД не требуют, и в графу можно поставить прочерк. Если же
введены цифры — считаем контрольные разряды, а не только длину: опечатка
вскроется уже отказом ФНС, а перестановка цифр — самая частая ошибка ввода.

Для бумажной доверенности (TYPE_POA) эти поля не показываются вовсе — там
представителя удостоверяет паспорт.
"""

from __future__ import annotations

from . import constants

# Веса контрольных разрядов ИНН физлица (12 цифр), по приказу ФНС.
_INN12_W11 = (7, 2, 4, 10, 3, 5, 9, 4, 6, 8)
_INN12_W12 = (3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8)


def digits(value: str | None) -> str:
    """Только цифры: пользователь вводит СНИЛС с дефисами и пробелом."""
    return "".join(ch for ch in (value or "") if ch.isdigit())


def _control(nums: list[int], weights) -> int:
    return sum(n * w for n, w in zip(nums, weights)) % 11 % 10


def is_valid_inn(value: str | None) -> bool:
    """ИНН физического лица — 12 цифр с двумя контрольными разрядами."""
    d = digits(value)
    if len(d) != 12:
        return False
    nums = [int(c) for c in d]
    return (
        _control(nums[:10], _INN12_W11) == nums[10]
        and _control(nums[:11], _INN12_W12) == nums[11]
    )


def is_valid_snils(value: str | None) -> bool:
    """СНИЛС — 11 цифр: 9 значащих + 2 контрольных.

    Контрольное число = сумма девяти цифр с весами 9…1 по модулю 101; 100 и 101
    записываются как 00 (правило ПФР)."""
    d = digits(value)
    if len(d) != 11:
        return False
    # Номера до 001-001-998 контрольного числа не имеют (историческое правило ПФР).
    if int(d[:9]) <= 1001998:
        return True
    checksum = sum(int(c) * (9 - i) for i, c in enumerate(d[:9])) % 101
    if checksum in (100, 101):
        checksum = 0
    return checksum == int(d[9:])


def format_snils(value: str | None) -> str:
    """СНИЛС в человеческом виде: XXX-XXX-XXX YY."""
    d = digits(value)
    if len(d) != 11:
        return (value or "").strip()
    return f"{d[0:3]}-{d[3:6]}-{d[6:9]} {d[9:]}"


def is_machine_readable(request_type: str, data=None) -> bool:
    """Машиночитаемая ли доверенность.

    «МЧД» в интерфейсе говорится в трёх местах: тип заявки, «тип доверенности»
    и «форма выдачи» в анкете. Инициатор пользуется любым из них — на dev уже
    есть доверенность, поданная как обычная, но с типом и формой МЧД. Для ФНС
    это одна и та же машиночитаемая доверенность, поэтому и требование об
    ИНН/СНИЛС одно, по любому из признаков.
    """
    if request_type == constants.TYPE_MCHD:
        return True
    d = data or {}
    return d.get("poa_type") == constants.TYPE_MCHD or d.get("form") == constants.TYPE_MCHD


def is_placeholder(value: str | None) -> bool:
    """«Значения нет»: пусто или прочерк.

    Для МЧД через Госуслуги ИНН и СНИЛС не нужны, и в бумажных бланках в такие
    графы ставят прочерк. Человек по привычке пишет «—», «-», «нет» — и раньше
    спотыкался о проверку контрольных разрядов. Считаем это отсутствием
    значения: цифр нет — проверять нечего.
    """
    return not digits(value)


def mchd_rep_error(data) -> str | None:
    """Ошибка анкеты МЧД по ИНН/СНИЛС представителя, либо None.

    Поля НЕ обязательные: на Госуслугах их для МЧД не требуют. Пустое значение
    и прочерк — не ошибка. Но если введены цифры, проверяем контрольные
    разряды: молча принять опечатку хуже, чем не иметь поля вовсе — вскроется
    она уже отказом ФНС.

    Возвращает текст, а не исключение: вызывающие оборачивают его в формат
    своего слоя (DRF-ошибка при сохранении, RequestError при отправке)."""
    rep = (data or {}).get("rep") or {}

    inn = rep.get("inn")
    if not is_placeholder(inn) and not is_valid_inn(inn):
        return "Проверьте ИНН представителя: должно быть 12 цифр, контрольный разряд не сходится."

    snils = rep.get("snils")
    if not is_placeholder(snils) and not is_valid_snils(snils):
        return "Проверьте СНИЛС представителя: должно быть 11 цифр, контрольное число не сходится."
    return None
